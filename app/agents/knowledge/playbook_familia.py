"""Base de conhecimento de atendimento e conversão em Direito de Família.

Playbook próprio de atendimento e fechamento para a área de Família (2026).
Fonte única dos agentes de atendimento a leads de divórcio, guarda/convivência,
alimentos e medida protetiva. Fundamentos-âncora dão segurança na CONVERSA;
não substituem a conferência do dispositivo/precedente na fonte oficial antes
do protocolo (regra da casa: validar jurisprudência antes de protocolar).

Tom da área: o lead de família chega emocionalmente exposto (separação,
disputa por filho, medo de violência). Postura acolhedora e NEUTRA sempre -
o agente nunca alimenta conflito entre as partes, nunca antecipa vitória e
nunca fala mal do "outro lado" mesmo quando o lead provoca.
"""

